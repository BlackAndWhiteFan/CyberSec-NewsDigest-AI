CONTEXT_PENALTY = 2

# Articles must reach this score to enter the digest: a critical (+3) or
# vulnerability (+2) match is required; Poland (+1) alone is not enough.
MIN_PRIORITY_SCORE = 2

DEFAULT_SOURCE_LIMIT = 4
SOURCE_LIMITS = {
    "niebezpiecznik.pl": 2,
}


def keyword_pattern(keyword):
    """Compile a stem-based keyword into a regular expression."""
    parts = []

    for word in keyword.split():
        if word.endswith("$"):
            parts.append(re.escape(word[:-1]) + r"(?!\w)")
        else:
            parts.append(re.escape(word) + r"\w*")

    return re.compile(r"(?<!\w)" + r"\W+".join(parts))


def compile_keywords(keywords):
    return tuple(keyword_pattern(keyword) for keyword in keywords)


CRITICAL_PATTERNS = compile_keywords(CRITICAL_KEYWORDS)
TITLE_ONLY_CRITICAL_PATTERNS = compile_keywords(TITLE_ONLY_CRITICAL_KEYWORDS)
VULNERABILITY_PATTERNS = compile_keywords(VULNERABILITY_KEYWORDS)
POLAND_PATTERNS = compile_keywords(POLAND_KEYWORDS)
EXCLUDED_TITLE_PATTERNS = compile_keywords(EXCLUDED_TITLE_KEYWORDS)
CONTEXT_TITLE_PATTERNS = compile_keywords(CONTEXT_TITLE_KEYWORDS)


def matches_any(text, patterns):
    return any(pattern.search(text) for pattern in patterns)


def categorize_article(article):
    """Return all categories matching an article's text."""
    title = article.get("title", "").casefold()
    description = article.get("description", "")
    text = f"{title} {description}".casefold()

    categories = []

    if matches_any(text, CRITICAL_PATTERNS) or matches_any(
        title, TITLE_ONLY_CRITICAL_PATTERNS
    ):
        categories.append("critical")

    if matches_any(text, VULNERABILITY_PATTERNS):
        categories.append("vulnerabilities")

    if matches_any(text, POLAND_PATTERNS):
        categories.append("poland")

    return categories


def prioritize_article(article):
    """Return a preliminary priority score based on matching keywords."""
    categories = categorize_article(article)
    score = 0

    if "critical" in categories:
        score += 3

    if "vulnerabilities" in categories:
        score += 2

    if "poland" in categories:
        score += 1

    if has_context_title(article):
        score -= CONTEXT_PENALTY

    return max(score, 0)


def has_context_title(article):
    """Return True when the title suggests an event, report or advice piece."""
    title = article.get("title", "").casefold()
    return matches_any(title, CONTEXT_TITLE_PATTERNS)


def is_excluded(article):
    """Return True for promotional content, based on the article title."""
    title = article.get("title", "").casefold()
    return matches_any(title, EXCLUDED_TITLE_PATTERNS)


def source_domain(article):
    """Return the article's domain without the www. prefix."""
    netloc = urllib.parse.urlparse(article.get("link", "")).netloc
    return netloc.lower().removeprefix("www.")


def source_limit(domain):
    return SOURCE_LIMITS.get(domain, DEFAULT_SOURCE_LIMIT)


def select_top_articles(articles, limit=20, min_score=MIN_PRIORITY_SCORE):
    """Return the highest-priority relevant articles, up to the limit.

    Promotional articles and articles below min_score are skipped, and no
    source may exceed its limit from SOURCE_LIMITS (or DEFAULT_SOURCE_LIMIT).
    The digest may therefore contain fewer articles than the limit.
    """
    if limit < 0:
        raise ValueError("limit must not be negative")

    candidates = [
        article
        for article in articles
        if not is_excluded(article) and prioritize_article(article) >= min_score
    ]
    ranked_articles = sorted(candidates, key=prioritize_article, reverse=True)

    selected = []
    per_source = {}

    for article in ranked_articles:
        if len(selected) >= limit:
            break

        domain = source_domain(article)

        if per_source.get(domain, 0) >= source_limit(domain):
            continue

        per_source[domain] = per_source.get(domain, 0) + 1
        selected.append(article)

    return selected
