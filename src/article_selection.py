def is_analysis_link(link):
    parsed = urllib.parse.urlparse(link)
    domain = parsed.netloc.lower().removeprefix("www.")
    return any(
        (domain == host or domain.endswith("." + host)) and parsed.path.startswith(prefix)
        for host, prefix in ANALYSIS_SOURCES
    )


def is_roundup(article):
    """True for a roundup kept in the digest ("Weekendowa lektura")."""
    return matches_any(article.get("title", "").casefold(), ROUNDUP_TITLE_PATTERNS)


def is_excluded(article):
    """Return True for promotional content, based on the article title."""
    title = article.get("title", "").casefold()
    return matches_any(title, EXCLUDED_TITLE_PATTERNS)


def source_domain(article):
    """Return the article's domain without the www. prefix."""
    netloc = urllib.parse.urlparse(article.get("link", "")).netloc
    return netloc.lower().removeprefix("www.")


def source_limit(domain):
    return SOURCE_LIMITS.get(domain, DEFAULT_SOURCE_LIMIT)


def relevant_articles(articles, min_score=MIN_PRIORITY_SCORE):
    """Return articles that are not promotional and reach min_score."""
    return [
        article
        for article in articles
        if not is_excluded(article) and prioritize_article(article) >= min_score
    ]


# v45 · Less, but better: the daily digest has at most DAILY_ITEMS items.
# CANDIDATES are summarized first, because merging duplicates after the
# summaries (v35, v44) still shortens the list.
DAILY_CANDIDATES = 14
DAILY_ITEMS = 10


def daily_rank(article):
    """Rank for the final cut: keyword score, a vulnerability from the CISA
    KEV catalog (+3), a CVE id (+1), other sources on the same story (+1
    each, at most 3) and a Polish source (+1)."""
    return (
        prioritize_article(article)
        + 3 * bool(article.get("kev"))
        + bool(article.get("cves"))
        + min(len(article.get("related", [])), 3)
        + source_domain(article).endswith(".pl")
        # v50: an item whose summary failed the checks goes last (Krebs on
        # Patch Tuesday, 11.11.2026, went out without a summary).
        - 3 * (not (article.get("summary") or "").strip())
    )


def limit_daily(articles, limit=DAILY_ITEMS):
    """Keep the `limit` best items in their original order (v45)."""
    if len(articles) <= limit:
        return articles

    ranked = sorted(range(len(articles)), key=lambda index: daily_rank(articles[index]), reverse=True)
    kept = sorted(ranked[:limit])
    dropped = [articles[index]["title"] for index in sorted(ranked[limit:])]
    print(f"LIMIT DNIA: {limit} z {len(articles)} pozycji; pominięte: " + " | ".join(title[:60] for title in dropped))
    return [articles[index] for index in kept]


def select_top_articles(articles, limit=20, min_score=MIN_PRIORITY_SCORE):
    """Return the highest-priority relevant articles, up to the limit.

    Promotional articles and articles below min_score are skipped, and no
    source may exceed its limit from SOURCE_LIMITS (or DEFAULT_SOURCE_LIMIT).
    The digest may therefore contain fewer articles than the limit.

    For a group of articles about the same event (see event_grouping), if
    the leading article's source has reached its limit, another article of
    the group from a source with room left represents the event instead.
    """
    if limit < 0:
        raise ValueError("limit must not be negative")

    candidates = relevant_articles(articles, min_score)
    ranked_articles = sorted(candidates, key=prioritize_article, reverse=True)

    selected = []
    per_source = {}

    for article in ranked_articles:
        if len(selected) >= limit:
            break

        members = [article] + list(article.get("related", []))
        chosen = next(
            (
                member
                for member in members
                if per_source.get(source_domain(member), 0)
                < source_limit(source_domain(member))
            ),
            None,
        )

        if chosen is None:
            continue

        if chosen is not article:
            others = [member for member in members if member is not chosen]
            chosen = dict(chosen)
            chosen["related"] = [
                {key: value for key, value in member.items() if key != "related"}
                for member in others
            ]

        if chosen.get("via"):
            if per_source.get("via", 0) >= LEKTURA_LIMIT:
                continue

            per_source["via"] = per_source.get("via", 0) + 1

        domain = source_domain(chosen)
        per_source[domain] = per_source.get(domain, 0) + 1
        selected.append(chosen)

    return selected
