def keyword_pattern(keyword):
    """Compile a stem-based keyword into a regular expression."""
    parts = []

    for word in keyword.split():
        if word.endswith("$"):
            parts.append(re.escape(word[:-1]) + r"(?!\w)")
        else:
            parts.append(re.escape(word) + r"\w*")

    return re.compile(r"(?<!\w)" + r"\W+".join(parts))


def compile_keywords(keywords):
    return tuple(keyword_pattern(keyword) for keyword in keywords)


