"""Rule-based article categorization, prioritization and selection.

Keywords are written as word stems: each word of a keyword matches any word
that starts with it, so "wyciek" matches "wycieku" and "wyciekiem", and
"krytyczn podatnoś" matches "krytycznej podatności". A word ending with "$"
must match a whole word, e.g. "luk$" matches "luk" but not "lukratywny".
Polish stems were checked against inflected forms generated by Morfeusz 2.

Scoring: critical +3, vulnerabilities +2, Poland +1. A title written in an
event, report or advice context (conference, experts, how-to guide...) loses
CONTEXT_PENALTY points, so such articles enter the digest only when they also
carry strong security signals.
"""

